"""**结果数字显示精度**的唯一定义处。

★ 为什么单独成一个模块（2026-10-10）
  评审要求「MAE 到 2–3 位小数」，我们定 **3 位**（= 4 位有效数字，1.45–3.04 的量级）。
  此前显示精度是**散落**的：`cn_thesis_text._f6` 一个、四个 latex 检查器里各有
  `round(..., 6)`、`make_tables.py` 里十来处 `'%.6f'`。改一次要同时改七八个地方，
  而**只改一半的后果是「检查器报错」**（显示 3 位、检查器比 6 位）**或更糟：
  两边都改、但改成了不同的位数**，那就成了自证。所以把它钉成一处。

  ⚠️ 比较侧与显示侧**必须用同一个函数**。`q()` 给检查器算期望值，`s()` 给生成器
     印字。两者都走 `'%.*f'`，不会各自漂开。

★ 刻意**不**受本模块管辖的数字（别顺手一起改了）
  · `论文_表格_全精度.md` —— 内部对账物，**保持 6 位**，它是独立锚点。
  · Δ 百分比（`%+.4f`）—— 量级 ~1.6%，4 位才看得出差别。
  · 保留比例（`0.999936`）与覆盖率区间（`0.986257..0.986821`）—— 是**分数**不是
    误差指标；3 位会变成 `1.000` 与 `0.986..0.987`，反而丢掉要说的那件事。

★ 从「旧字面量」改印新精度时当心**二次舍入**：`'%.3f' % float('1.464500')`
  与 `'%.3f' % 1.4644999…` 在 `x.xxx5` 边界上可能差 1。所以改完 .tex 之后，
  一定要跑那四个检查器 —— 它们比的是 `q(JSON 原始值)`，正好是二次舍入的独立仲裁。
"""

Q = 3


def q(x):
    """数值形式：给检查器算期望值用（与 `s()` 用同一条 `'%.*f'` 规则）。"""
    return float('%.*f' % (Q, x))


def s(x):
    """字符串形式：给生成器/转换脚本印字用。"""
    return '%.*f' % (Q, x)
